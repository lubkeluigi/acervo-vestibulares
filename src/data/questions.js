const matchesTaxonomySelection = (value, selection, emptyLabel) => {
  if (Array.isArray(selection)) return selection.length === 0 || selection.includes(value);
  return !selection || selection === emptyLabel || selection === value;
};

export const getContents = (subject) => [...new Set(
  questions.filter((q) => matchesTaxonomySelection(q.subject, subject, 'Todas')).map((q) => q.content),
)].sort();

export const getSubtopics = (subject, content) => [...new Set(
  questions.filter((q) =>
    matchesTaxonomySelection(q.subject, subject, 'Todas') &&
    matchesTaxonomySelection(q.content, content, 'Todos'),
  ).map((q) => q.subtopic),
)].sort();
